// Write src/<Game>/StarterBases.elm from the starter .mpd files: the vehicle
// editor starts from them and elm-test checks them (Elm cannot read files).
// Run from the repo root:
//   node starters/embed-starters.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';

const [dir, out, moduleName] = process.argv.slice(2).length
  ? process.argv.slice(2)
  : defaults(GAME_DIR());

// `starters/racer` -> `src/Racer/StarterBases.elm`, module `Racer.StarterBases`.
function defaults(gameDir) {
  const game = gameDir.split('/').pop();
  const ns = game.charAt(0).toUpperCase() + game.slice(1);
  return [gameDir, `src/${ns}/StarterBases.elm`, `${ns}.StarterBases`];
}

function GAME_DIR() {
  return readdirSync('starters', { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => join('starters', d.name))
    .find((d) => readdirSync(d).some((f) => f.endsWith('.mpd')));
}

const files = readdirSync(dir).filter((f) => f.endsWith('.mpd')).sort();
const entries = files.map((f) => {
  const text = readFileSync(join(dir, f), 'utf8');
  return `    { file = ${JSON.stringify(f)}\n      , text = ${JSON.stringify(text)}\n      }`;
});

const elm = `module ${moduleName} exposing (Starter, all)

{-| The starter bases in \`${dir}/\`, embedded as text: the vehicle editor
starts from them and the tests check them.
Generated by \`node starters/embed-starters.mjs\`; do not edit by hand.
-}


{-| A starter base file and its LDraw text.
-}
type alias Starter =
    { file : String
    , text : String
    }


{-| Every starter base, by file name.
-}
all : List Starter
all =
    [ ${entries.join('\n    , ').trimStart()}
    ]
`;
writeFileSync(out, elm);
// Keep `make check` (elm-format --validate) happy.
const fmt = spawnSync('elm-format', ['--yes', out], { stdio: 'ignore' });
if (fmt.status !== 0) console.warn('elm-format not found or failed: run `elm-format --yes ' + out + '`');
console.log(`wrote ${out} (${files.length} starters)`);
